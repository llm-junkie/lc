/**
 * JS-side tool types.
 *
 * Separate from `src/modules/llm-client/types.ts` because these carry the runtime
 * concerns (zod schemas and execution logic) that the
 * wire format doesn't know about. The mapper in `registry.ts`
 * (`materialize()`) takes a `ToolHandler[]` and projects it to
 * `ToolDefinition[]` for the wire.
 */
