// Phase 2.4 — Unified discriminated result envelope
// ═══════════════════════════════════════════════════════════════════

/**
 * Discriminated tool result status.
 * Replaces the `is_error` boolean with precise terminal states.
 *
 *   - `ok`: all sub-operations succeeded; data is complete.
 *   - `partial`: mixed batch — some items succeeded, some failed.
 *     The issues array carries per-item failure details.
 *   - `error`: all-item failure; no usable data.
 *   - `aborted`: cancelled by user before completion.
 *   - `timeout`: exceeded the per-call deadline.
 */
export type ToolStatus = 'ok' | 'partial' | 'error' | 'aborted' | 'timeout';

/**
 * A structured issue within a tool result.
 *
 * Phase 2.4 replaces string-scraping for paths and error codes
 * with explicit, machine-readable issue descriptors.
 */
export interface ToolResultIssue {
  /** Stable error/success code (e.g. 'path_outside_roots', 'too_large'). */
  code: string;
  /** Human-readable description for the model and user. */
  message: string;
  /** Affected path (file, dir, URL, etc.), if applicable. */
  path?: string;
  /** True only when repeating the same call may succeed without correction. */
  retryable?: boolean;
  /** Native OS error code retained from the launch boundary, when available. */
  native_code?: number | string;
  /** Native OS error text retained from the launch boundary, when available. */
  native_reason?: string;
  /** Executable involved in a launch failure, when applicable. */
  executable?: string;
  /** Machine-readable replacement input. It is never executed implicitly. */
  suggested_call?: Record<string, unknown>;
  /** One short action that can correct or terminate this failure. */
  remedy?: string;
  /** Exact arguments for detailed guidance about the affected tool. */
  help?: {
    tool: string;
    query: string;
  };
  /** Bounded alternatives for an unknown operational tool name. */
  suggestions?: Array<{
    tool: string;
    purpose: string;
  }>;
  /** Executable name that the corrected call must satisfy in the allowlist. */
  required_allowlist_entry?: string;
}

/**
 * Unified discriminated result envelope for all tool executions.
 *
 * Design contract (Phase 2.4, GPT §3.8):
 *   - Every tool result has exactly one `status`.
 *   - `issues` is empty for `ok`. Every other status identifies its issue.
 *   - Per-item errors in batch tools propagate truthfully.
 *   - Provider/network/protocol errors remain distinguishable
 *     from tool-logic errors.
 *   - String-scraping for `path_outside_roots` etc. is removed;
 *     callers consume `issues[].code` and `issues[].path` instead.
 */
export interface ToolResultEnvelope<T = unknown> {
  /** Discriminated terminal status. */
  status: ToolStatus;
  /** Tool output data. Present for `ok` and `partial`; absent for
   *  `error`, `aborted`, `timeout`. */
  data?: T;
  /** Structured issues. Empty only for `ok`. */
  issues: ToolResultIssue[];
  /** Non-blocking warnings (for example, truncated output). */
  warnings: string[];
  /** Optional execution metrics. */
  metrics?: {
    durationMs: number;
    bytesRead?: number;
    bytesWritten?: number;
  };
}

/**
 * Serialize a ToolResultEnvelope into the string that gets stored
 * as a `role: 'tool'` message. The model sees this JSON so it can
 * adapt to structured error codes on the next turn.
 *
 * Phase 2.4: Structured terminal results keep status and issue codes
 * together instead of making callers infer policy failures from strings.
 * Plain successful handler values remain supported as normal tool payloads.
 */
export function serializeEnvelope(env: ToolResultEnvelope): string {
  return JSON.stringify(env);
}

/**
 * Build a simple ok envelope from a tool's output value.
 */
export function okEnvelope<T>(data: T, durationMs: number, warnings?: string[]): ToolResultEnvelope<T> {
  return {
    status: 'ok',
    data,
    issues: [],
    warnings: warnings ?? [],
    metrics: { durationMs },
  };
}

/**
 * Build an error envelope with structured issues.
 */
export function errorEnvelope(
  issues: ToolResultIssue[],
  durationMs: number,
  warnings?: string[],
): ToolResultEnvelope<never> {
  return {
    status: issues.length === 0 ? 'error' : 'error',
    issues,
    warnings: warnings ?? [],
    metrics: { durationMs },
  };
}

/**
 * Build an aborted envelope.
 */
export function abortedEnvelope(durationMs: number): ToolResultEnvelope<never> {
  return {
    status: 'aborted',
    issues: [{ code: 'aborted', message: 'Operation cancelled by user.' }],
    warnings: [],
    metrics: { durationMs },
  };
}

/**
 * Build a timeout envelope.
 */
export function timeoutEnvelope(durationMs: number): ToolResultEnvelope<never> {
  return {
    status: 'timeout',
    issues: [{ code: 'timeout', message: 'Operation exceeded the time limit.' }],
    warnings: [],
    metrics: { durationMs },
  };
}
