/**
 * Build script: reads the skill Markdown files from skills/ and generates
 * `src/modules/builtin-skill-content.ts` with the content embedded as
 * template-literals with backtick characters properly escaped.
 *
 * Run with: node scripts/build-skills-content.mjs
 *
 * This is called automatically by `npm run build` and should be re-run
 * whenever a skills/*.md file changes.
 */

import { readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SKILLS_DIR = resolve(ROOT, 'skills');
const OUT_FILE = resolve(ROOT, 'src', 'modules', 'builtin-skill-content.ts');

const SKILL_FILES = [
  'lc_skill_lc_tools.md',
  'lc_skill_mermaid-diagram.md',
  'lc_skill_svg-generation.md',
  'lc_skill_ste100.md',
];

const VAR_NAMES = [
  'LC_TOOLS_MD',
  'MERMAID_MD',
  'SVG_MD',
  'STE100_MD',
];

const LC_TOOLS_SECTIONS = [
  'core',
  'file_io',
  'shell',
  'web_access',
  'whiteboard',
  'tool_history',
  'skills',
];

const TRANSIENT_WRITE_CODES = new Set(['EACCES', 'EBUSY', 'EPERM', 'UNKNOWN']);
const WRITE_ATTEMPTS = 8;

function waitBeforeRetry(attempt) {
  return new Promise((resolveDelay) => setTimeout(resolveDelay, attempt * 25));
}

async function writeGeneratedFile(path, content) {
  for (let attempt = 1; attempt <= WRITE_ATTEMPTS; attempt += 1) {
    try {
      if (readFileSync(path, 'utf-8') === content) return false;
      break;
    } catch (error) {
      if (error?.code === 'ENOENT') break;
      if (!TRANSIENT_WRITE_CODES.has(error?.code) || attempt === WRITE_ATTEMPTS) throw error;
      await waitBeforeRetry(attempt);
    }
  }

  for (let attempt = 1; attempt <= WRITE_ATTEMPTS; attempt += 1) {
    try {
      await writeFile(path, content, 'utf-8');
      return true;
    } catch (error) {
      if (!TRANSIENT_WRITE_CODES.has(error?.code) || attempt === WRITE_ATTEMPTS) throw error;
      await waitBeforeRetry(attempt);
    }
  }

  return false;
}

function validateLcToolsTemplate(raw, filename) {
  const lines = raw.split(/\r?\n/);
  const markerPattern = /^<!-- lc-tools-section:([a-z_]+) -->$/;
  const markerLines = lines
    .map((line, index) => ({ line, index }))
    .filter(({ line }) => line.includes('lc-tools-section:'));
  const markers = markerLines.map(({ line, index }) => {
    const match = markerPattern.exec(line);
    if (!match) throw new Error(`${filename}:${index + 1} has an invalid LC Tools section marker`);
    return { key: match[1], index };
  });

  if (markers.length !== LC_TOOLS_SECTIONS.length) {
    throw new Error(`${filename} must contain exactly ${LC_TOOLS_SECTIONS.length} LC Tools sections`);
  }
  for (let index = 0; index < LC_TOOLS_SECTIONS.length; index += 1) {
    const expected = LC_TOOLS_SECTIONS[index];
    const marker = markers[index];
    if (marker.key !== expected) {
      throw new Error(`${filename} section ${index + 1} must be ${expected}, found ${marker.key}`);
    }
    const end = markers[index + 1]?.index ?? lines.length;
    if (!lines.slice(marker.index + 1, end).join('\n').trim()) {
      throw new Error(`${filename} section ${expected} must not be empty`);
    }
  }
}

function escapeForTemplateLiteral(text) {
  // Escape backticks, backslashes, and dollar-brace sequences
  // that would be interpreted inside a template literal.
  return text
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
}

const sections = [];

for (let i = 0; i < SKILL_FILES.length; i++) {
  const filePath = resolve(SKILLS_DIR, SKILL_FILES[i]);
  const raw = readFileSync(filePath, 'utf-8');
  if (VAR_NAMES[i] === 'LC_TOOLS_MD') validateLcToolsTemplate(raw, SKILL_FILES[i]);
  const escaped = escapeForTemplateLiteral(raw);
  sections.push(`export const ${VAR_NAMES[i]} = \`${escaped}\`;`);
}

const output = `/**
 * Built-in skill Markdown content — shipped with LC.
 *
 * These are the raw Markdown sources for LC's built-in skills.
 * This file is AUTO-GENERATED from the \`skills/\` directory by
 * \`scripts/build-skills-content.mjs\`.
 *
 * DO NOT EDIT THIS FILE DIRECTLY.
 * Edit the .md files in \`skills/\` and re-run the build script:
 *   node scripts/build-skills-content.mjs
 */

${sections.join('\n\n')}

/** All built-in skill sources as raw Markdown strings. */
export const BUILTIN_SKILL_SOURCES: readonly { raw: string; filename: string }[] = [
${SKILL_FILES.map((filename, index) => `  { raw: ${VAR_NAMES[index]}, filename: '${filename}' },`).join('\n')}
];
`;

const wroteOutput = await writeGeneratedFile(OUT_FILE, output);
console.log(`[build-skills-content] ${wroteOutput ? 'Wrote' : 'Current'} ${OUT_FILE}`);
